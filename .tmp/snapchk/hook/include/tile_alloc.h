#ifndef TILE_ALLOC_H
#define TILE_ALLOC_H

#include <stdint.h>
#include "game.h"

/* ---- 12px 行相位（唯一保留的状态）-----------------------------------------
 * 相位是「行内像素游标」px（phase = px & 7）：12px 步进不是 8px 的整数倍，
 * 字形必然跨 tile 列。相位属于**一行**，不属于窗口/文本块，逐字切换窗口时
 * 必须失配归零，故用「单变量 + 行标识（win ^ tpl ^ curY ^ curTileY）」表达。
 *
 * 🔴 v21：行相位**不再与任何 tile 号绑定**。tile 号现在是位置的纯函数
 *    （`TILE_BASE + TILE_OFFSET`），所以旧 `v8_phase_last_tile()`（跨调用传
 *    「上一字尾列号」的全局单例）已删除 —— 它是「号不可算」时代的产物。 */

/* 取当前行内相位 px（内部先按 win 校验行标识，失配即归零）。phase = px & 7。 */
uint16_t v8_phase_get(TextPrinter *win);

/* 推进相位 px += adv（adv = 本字步进像素）。 */
void v8_phase_advance(uint16_t adv);

/* 显式复位行相位（渲染层在换行控制码 FA/FB/FE 上直调）。
 *
 * 为什么需要「显式」：v8_phase_get 的行标识（win^tpl^curY^curTileY）是**间接**
 * 检测，依赖引擎在取下一行首字之前就把 curY/curTileY 推到位。官方 FE 的时序是
 * 「先推一个、另一个稍后才变」，存在漏检窗口；一旦漏检，下一行首字会带着上一行
 * 的累计相位起步（累计 = 12n mod 8，n 为奇数时 = 4），实机表现为
 * 「奇数个字的一行，换行后行尾只剩半个字」。本函数不依赖时序，是那条链的兜底。 */
void v8_phase_reset(void);

#endif /* TILE_ALLOC_H */
