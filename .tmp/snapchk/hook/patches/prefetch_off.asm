; =============================================================================
; [P32] 关闭日文字形「预取」——把 worker 0x080029E0 入口短接成「立即返回 1」
;
; 为什么必须关（v21 位置定号下它是唯一的画布污染源）
; ==================================================
; 0x080029E0（worker）与 0x08002A50（InitWindowTileData）配套：
;     0x080029E2  ldr r0,[0x03000328]   ; = win->[0] = tpl 指针
;     0x080029E6  ldrb r0,[r0,#9]       ; = tpl->textMode
;     0x080029E8  cmp r0,#0 / beq  →  0x08002A48: movs r0,#1 ; return 1
;     0x080029F4  cmp r0,#2 / bge  →  同上
;     ...仅 tm==1 落到加载分支：
;     0x08002A08..A22  循环 16 次：
;         r0 = *(0x03000328)                 ; tpl
;         r1 = *(u16*)0x0300032C             ; startOffset（0,16,32,...,240）
;         r2 = (u8)r4                        ; glyphIdx
;         bl 0x08002A50                      ; InitWindowTileData(tpl,start,idx)
;                        → dst = tpl->tileData + start*32 + idx*64
;                          即把日文字形**图集**灌进 tpl 那个 charBlock 的**低号段**。
;
; 🔴 而 v21 之后，我们窗口的 tile 号 = `win[0x16] + win[0x18]`，
;    物理落点 = `tpl->tileData + 号*32` —— **同一个 charBlock、同一段号空间**。
;    也就是说：这个预取会**直接盖掉我们池子（[0,384)）里的中文砖**。
;    它是「撞 UI / 文字散架」在 v21 下仅存的官方写入源。
;
; 为什么改这里而不是改 36 条模板的 tpl[9]（原 15-2 Step1，已废）
; ==============================================================
; 把 tm 1→0 确实能让本 worker 直接 return，**但** FontFuncTable[0] 的处理器
; 同时会被启用，而它是「自己画」的那个：
;     FontFunc[0] 0x08003568 → bl 0x08003520
;       0x08003524  dst = tpl->tileData + (win[0x16] + win[0x18]) * 32
;       0x08003542  bl 0x08003630 (DrawGlyphTiles)   ← 把**日文字形 blit 到我们的号上**
;       0x08003570  win[0x18] += 2                   ← 叠加在我们自己的推进上
; 对比 FontFunc[1] 0x0800360C（tm1）：经 FontSubTable[fontNum] **只调 UpdateTilemap**，
; 不碰任何 VRAM、不动 win[0x18]（game_addrs.asm:68 早已记录此差异）。
; ⇒ tm1→tm0 = 用一个更糟的副作用换掉一个更好的（本来就能单点关掉的）副作用。
;
; ⇒ 结论：**保持 tm1 不动**（53 条模板零改动），只在本 worker 的入口短接。
;    tm==0 时本 worker 的返回路径就是 `movs r0,#1; bx lr`（0x08002A48/A4E），
;    所以本补丁与该 gate 的行为**逐字节等价**。
;
; 安全性
; ======
; · 覆盖 0x080029E0..E3 = 原 `push {r4,lr}`（2B）+ `ldr r0,[pc,#28]`（2B），
;   两者都只服务于本函数序言，不被任何跳转表指向。
; · 调用点全 ROM 仅 2 处 BL（0x080685E0 / 0x0806F01C），**零** `|1` 函数指针引用。
; · 桩不 push / 不 pop / 不触栈，`bx lr` 直返（原路径栈净额同为 0）。
;   🔴 不是 `mov lr,pc` 模拟 bl（铁律 6），本桩根本不跳别处。
; · 返回 1 = 与 tm0 gate 完全一致，调用方 `cmp r0,#0 / bne` 判定不变。
; =============================================================================

.org 0x080029E0
    .halfword 0x2001        ; movs r0, #1   ← 「预取已完成」返回值，与 tm0 gate 一致
    .halfword 0x4770        ; bx   lr
; 用 .halfword 而非助记符：armips 的 .thumb 是非 unified 语法，
; 不接受 `movs`；写成机器码可 100% 确定落地字节（本补丁的验收就是这 4 字节）。
