-- ============================================================================
-- memdump.lua — 进游戏后把 EWRAM/IWRAM/VRAM 全量 dump 出来（用于查 F7 表）
--
-- ── 为什么需要它 ────────────────────────────────────────────────────────────
-- 静态分析发现转码函数 @0x081DB660 里有：
--     ldr  r7,[pc,#112]   @ 字面量 0x081DB6D8 = 0x0203F2C0
--     ldrb r0,[r5,#0]     ; hi = F7 之后那一字节
--     lsls r0,r0,#2       ; hi * 4
--     adds r0,r0,r7
--     ldr  r1,[r0,#0]     ; ptr = TABLE[hi]
--     …逐字节复制 ptr 指向的串…
-- 且 0x081DB6D8 的**原版值是 0x00000000**，说明这是汉化改的。
--
-- 但那张表在 EWRAM（0x0203F2C0），ROM 里没有静态副本。
-- ⇒ 必须**把运行中的 EWRAM 原样抓下来**才能看 TABLE 里到底是什么。
--
-- ── 要验证的假设 ────────────────────────────────────────────────────────────
--   H1  TABLE[hi] 指向的都是「原版单字节字符序列」
--       ⇒ 汉化用原版字符拼中文（不需要中文字模）
--   H2  TABLE[hi] 指向的是**压缩数据**，要运行时解压/展开
--       ⇒ 存在解压算法，不能简单说「拼字符」
--
-- 只 dump 内存，不截图 —— 目标是把 0x0203F2C0 那段原样拿到。
-- ============================================================================

local L = dofile((os.getenv("BOT_ROOT") or "."):gsub("\\", "/"):gsub("/+$", "")
                 .. "/scenes/" .. os.getenv("BOT_GAME_ID") .. "/_lib.lua")
local api = L.new()

-- ① 等冷启动标题站稳，再按 A 进主菜单（沿用 play.lua 的时序，已验证可用）
api.wait(2800)
api.tap("START", 10, 220)
api.tap("A", 8, 260)

-- ② 连按 A 穿过开场（play.lua 实测 10 轮足够落到游戏世界）
for i = 1, 10 do
    api.tap("A", 6, 150)
end

-- ③ 落稳后：先 dump 一次「还没进任何菜单」的状态
api.wait(240)
api.shot("stage1_world")

-- ④ 再按 START 打开系统菜单 —— 菜单里的文字是 F7 编码最密集的地方，
--    此时 TABLE 一定已被填充好
api.tap("START", 10, 180)
api.shot("stage2_menu")

-- ⑤ 再按 B 退出，多抓一个状态（确认 TABLE 内容稳定不随界面变）
api.tap("B", 6, 120)
api.wait(120)
api.shot("stage3_back")

return api.S
