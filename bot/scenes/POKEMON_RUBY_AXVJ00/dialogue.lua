-- ============================================================================
-- dialogue.lua — 柜台对话（长文本 / 逐字打印 / 多句重写 / 商店菜单）
--
-- 【默认存档】MauvilleCity_Mart_3-3.sav（见 saves/scene_saves.json）
--   室内商店，起点 (3,3)，**左侧**柜台后有店员 → 转身向左按 A 即可对话。
--
-- 【为什么必须换到室内】（两次实测教训）
--   1) 野外版（Route118）走到 NPC 面前要穿过草丛，按 A 时直接触发野生遭遇：
--      translated 侧拍到的是战斗转场，origin 侧还停在野外 —— 两侧根本不在
--      同一界面，却照样被记成 11 对合法对照。
--   2) 更根本的是 RNG：两侧文字打印耗时不同 ⇒ settle 时长不同 ⇒ 按键落在
--      不同的游戏帧 ⇒ 遭遇判定必然分岔。**带 RNG 的场景不能当对照。**
--   室内无草丛、NPC 站位固定，是对话类唯一的稳定现场。
--
-- 【为什么必须做这个场景】（BUG 2：文字打印残留）
--   对话是所有文本面里唯一「同一块窗口反复重写」的地方：新一句比旧一句短
--   时旧句尾部必须清掉，清不干净就是残留。12px = 8+4 / 4+8 的半格拼接下，
--   一个汉字跨 tile 边界，清行时很容易只清掉自己写过的那一半。
--
--   本场景安排四段重写压力：
--     ① 逐字打印完成后的整句
--     ② 用 A 推进到下一句（短句覆盖长句）
--     ③ 商店菜单把「对话框 + 菜单框」两个窗口同时拉起来（最容易撞）
--     ④ 关掉后**再开一次**（整块窗口重画，检查旧字有没有被带出来）
--
-- 【闸门】开框走 talk（等「文本真的在推进」：新窗口 / 文本指针变化 /
--   打印下标变化）。按 A 打空会当场失败，不再产出静默无效的假对照。
--
-- ⚠ 全程不确认购买：只用 A 推两句，之后一律用 B 退，避免改变金钱/道具。
-- ============================================================================
local L = dofile((os.getenv("BOT_ROOT") or "."):gsub("\\", "/"):gsub("/+$", "")
                 .. "/scenes/" .. os.getenv("BOT_GAME_ID") .. "/_lib.lua")
local api = L.new()

L.preamble(api)              -- 含 prove
api.shot("overworld")        -- 商店内，日志里有 [POS] grid=(3,3)

-- ── ① 转身向左（6 帧只够转身，走不动一格）→ 开对话（硬闸门）──────────────
api.tap("LEFT", 6, 40)
api.talk{ timeout = 300 }
api.wait(60)
api.shot("dlg_welcome")      -- 第 1 句（打印完成）

-- ── ② 推进：A 进商店菜单 → A 进购买列表（对话框 + 列表 + 底部说明同屏）──────
api.tap("A", 4, 50)
api.shot("dlg_shopmenu")
api.tap("A", 4, 50)
api.shot("dlg_buylist")

-- ── ③ 退出：B 退购买列表 → B 退商店菜单 → 告别语 → 关掉 ────────────────────
api.tap("B", 4, 45)
api.shot("dlg_back1")
api.tap("B", 4, 45)
api.shot("dlg_farewell")
api.tap("A", 4, 45)
api.shot("dlg_back_overworld")

-- ── ④ 再开一次：同一段文字从头重写，检查旧字/旧 tile 有没有被带出来 ───────
api.tap("LEFT", 6, 30)
api.talk{ timeout = 300 }
api.wait(60)
api.shot("dlg_reopen")
api.tap("B", 4, 45)
api.tap("B", 4, 45)
api.shot("dlg_closed2")

return api.S
