; =============================================================================
; [P40] 血条「Lv」收尾：去掉冒号，让 Lv 顶上冒号的位置
; -----------------------------------------------------------------------------
; 用户 2026-11-26 定的方案：
;   「去掉 ：，然后 Lv 顶上原本 ：的位置」
;
; ── 屏幕结构（GDB + VRAM 实测，2026-11-26）──────────────────────────────
;   敌方血条 obj7：tileNum=128，覆盖屏幕 x12..75
;   敌方血条 obj8：tileNum=160，覆盖屏幕 x76..139
;   「Lv」画在 obj7 的 tile143（= obj7 名字区第 7 格），屏幕 x68..75
;   冒号「:」是元素 elem 0x2A（ROM 0x0868F120），由 sub_8043FC0
;     在 0x08041288 处 CpuSet 到 obj8 的 tile168，屏幕 x76..83
;   数字「13」由同函数第二个循环写到 tile169/170
;
; ── 本补丁做什么 ───────────────────────────────────────────────────────
;   把 elem 0x2A（冒号 32B 图案）就地换成「Lv」图案（32B）。
;   冒号因此消失，Lv 出现在原来冒号的位置（x76..83），
;   与后面的数字连成「Lv13」，中间不再有冒号。
;
;   配套改动（见 src/battle/NickFullName_entry.s 的 NickCopyCellsAlt_Hook）：
;   敌方名字区固定补满第 7 格并把该格 dn 片填血条底色，
;   把底图自带的那个 Lv（tile143）抹掉，避免出现两个 Lv。
;
; ── 图案来源（全部实测）──────────────────────────────────────────────────
;   冒号 elem 0x2A @0x0868F120（原值，32B）：
;     22×8B, then 22 12 21 22 / 22 12 41 22 / 22 22 44 22 重复两遍
;     → 屏幕上就是两个上下排列的点（冒号）
;   Lv 图案 = 日版 VRAM 044 帧 tile143 的实测内容：
;     22 22 22 22 | 22 22 22 22 | 12 21 22 22 | 12 31 22 22
;     12 31 12 12 | 12 31 22 31 | 12 11 21 23 | 22 33 33 22
;     → L 在 col0-1，v 在 col4-6，一个 8px 格装得下
;
; ⚠ 这个地址是「健康箱元素表」的一项，被 CpuSet 到 OBJ VRAM。
;   改内容不改指针 ⇒ 不影响任何寻址逻辑，纯数据改动。
; =============================================================================

.org 0x0868F120
    ; row0
    .byte 0x22, 0x22, 0x22, 0x22
    ; row1
    .byte 0x22, 0x22, 0x22, 0x22
    ; row2  L 起笔
    .byte 0x12, 0x21, 0x22, 0x22
    ; row3
    .byte 0x12, 0x31, 0x22, 0x22
    ; row4  L 底横 + v 起笔
    .byte 0x12, 0x31, 0x12, 0x12
    ; row5
    .byte 0x12, 0x31, 0x22, 0x31
    ; row6  L 底横 + v 收笔
    .byte 0x12, 0x11, 0x21, 0x23
    ; row7  底边
    .byte 0x22, 0x33, 0x33, 0x22
