; =============================================================================
; [P10] 战斗血条名字：改用 species 查新表拿完整中文名（BUG-8 根治）
; -----------------------------------------------------------------------------
; 0x08042408 原流程：
;   08042430  bl GetMonData(mon, 2, sp)   ← param 2 = nickname[10]，只拷 10B
;   08042436  bl StringCopyN(sp, 5)       ← 再截断到 5B
;
; nickname[10] 是 Gen3 存档定长字段（+8，紧跟 +18 language / +19 flags），
; 中文 3 字 = 12B 塞不下 → 第 3 字被砍成半个（实测 0x0102 + 越界残片 75）。
; 改 cmp 上限会越界写坏 language/flags → 战斗流程挂死（实测 f=6899 超时）。
;
; 火红 0x08053358 的解法：显示与存档解耦 —— 存档写 nickname，显示按 species
; 查新表。我们等价物已齐：
;   GetMonData(mon, 11) = 0x08039F24  → species
;   0x0803B11C(dst, species)          → 按 species 从 0x1EB0AF4 拷完整名，遇 FF 停
;
; 只替换 0x08042430 那一个 bl（4B），逻辑见 src/battle/NickFullName_entry.s。
; nickname[10] 一字节不动 → 存档仍写原版编码 → 串档不乱。
; =============================================================================

; =============================================================================
; [P12] 遭遇文本「野生的XXX」：用 species 查新表写完整名
; -----------------------------------------------------------------------------
; 0x0811C7AA = bl GetMonData(mon, 2, sp)，是 FD 03（物种名占位符）的展开点。
; 源 nickname[10] 装不下 3 汉字 → 第 3 字只有半个，后面是越界残渣。
; 本 hook 换成「species → 新表 0x1EB0AF4」，完整名自带 FF，
; 后续 0x0811C7B0 的 StringCopyN 遇 FF 即停，不会截断。
;
; 0x0811C7AA → 0x08800000 距 7.2MB，超 bl 的 ±4MB，两级跳：
;   bl 到 0x081B504C（距 0.6MB）→ ldr/bx 到 game.bin
; 0x081B504C 在原版 355B 连续 0x00 空洞内，未被任何 .org 占用。
; =============================================================================

.org 0x0811C776
    bl NickSlot_Tramp

.org 0x081B504C
NickSlot_Tramp:
    ldr r3, =(NickSlot_Hook | 1)
    bx  r3
.pool
