; AXVJ 地址（GDB 实测）：0x0806B288
;   入口 12 次（6 只 x 2 次重绘）：r0=monIndex, r1=0, r2=nameBuffer(0x03007DC8)
;   前 4 条（8 字节，被跳板覆盖）：
;     0x0806B288  B510  push {r4,lr}
;     0x0806B28A  B081  sub sp,#4
;     0x0806B28C  0600  lsls r0,#24
;     0x0806B28E  0609  lsls r1,#24
;   之后从 0x0806B290 的 0E09 继续。
;
; ── 跳板布局（字面量必须落在 0x0806B28C）──────────────────────────────
;   0x0806B288: 4B00  ldr r3,[pc,#0]   PC=(0x0806B288+4)&~3 = 0x0806B28C
;   0x0806B28A: 4718  bx r3
;   0x0806B28C: <hook|1>  4B 字面量（覆盖原 0600/0609，这两条在 hook 里重放）
;
; ── ★ 曾经的致命 bug（2026-11-23，前八次失败的真因）──────────────────
; hook 里 pop {r3} 把调用者返回地址弹出后**丢弃**，接着重放
; push {r4,lr} —— 但此时 lr 已是 bl 之后的假值（指向 hook 内部）。
; 原函数把这个假 lr 入栈，返回时跳回 hook 内部
; ⇒ 只执行 1 次就偏离流程（GDB：应为 12 次，实际 1 次）。
; 修法：pop {r3} 后 mov lr, r3。
; 诊断方法：让查表函数永远返回 0（完全不替换数据），仍只命中 1 次
; ⇒ 证明问题在 hook 机制而非中文数据。**改渲染层先验证空操作版等价性。**
;
; ── 蛋（species 0）────────────────────────────────────────────────────
; 蛋显示「タマゴ」，它**不在物种名表里**（是硬编码串），所以查表查不到。
; 这里在 0x081B5100 写一份「蛋」的中文串，hook 里对 タマゴ 特判返回它。
;
; ── 已证伪的旧路线（别再走）──────────────────────────────────────────
; ① hook 0x0803B11C（日文表 species*6）：GDB 命中 0 次。
; ② PrintNextChar 字符流换源：WIN_STATE 到不了 END → 输入回调停摆。
; ③ Text_InitWindow(0x08002C68) 入口：通用函数每场景 160 次 → 开始菜单卡死。
; ④ 让 GetMonNickname 返回中文指针：调用者忽略返回值（实测）。
; ⑤ 在 0x0806B2E4 改 r2：停摆。
; ⑥ 本函数里调 GetMonData 算 species：队伍界面全黑。
;
; 存档完全不碰 → 串回日版不乱码（与 P10/P12 同一原则）。
; =============================================================================
