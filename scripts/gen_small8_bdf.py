"""gen_small8_bdf.py — 生成原生 8x8 汉字的 BDF（给 GBA fontNum=4 小字用）

为什么需要它
------------
GBA 的 fontNum=4 是 **8x8 tile** 标准小字，步进必须 8px 才能与硬件 tile
网格对齐。现有 small.bdf 是 9x9 墨迹，压到 8x8 会毁字形（面积平均吞行成
实心横杠、最近邻断笔画，均实测）。

做法：用系统 TTF 在小字号下**重新栅格化**出 8x8 点阵，而不是从 9x9 缩。
- 源字体：SimSun（宋体，小字号比黑体更清晰，笔画不易糊）
- 目标：墨迹恰好占 8x8（不是 16x16 容器，直接 8x8）
- 阈值：按覆盖率二值化，保证细笔画不断

输出 BDF 的 FONTBOUNDINGBOX 是 8x8，与 GBA tile 一致。

用法：
    python scripts/gen_small8_bdf.py \
        --out configs/POKEMON_RUBY_AXVJ00/fonts/small8.bdf \
        --charmap configs/POKEMON_RUBY_AXVJ00/charmap.txt
"""
from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

SIZE = 8


def load_charset(charmap: Path) -> list[str]:
    """从 charmap.txt 取所有单字（去重、保持顺序）。"""
    seen: dict[str, None] = {}
    for line in charmap.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if "=" not in line:
            continue
        _, _, ch = line.partition("=")
        ch = ch.strip()
        if len(ch) == 1 and ord(ch) > 0x7F:
            seen.setdefault(ch, None)
    return list(seen.keys())


def render_glyph(ch: str, font_path: Path) -> tuple[list[int], int, int]:
    """把单字渲染成 8x8 点阵，返回 (位图行, 墨迹宽, 墨迹高)。

    做法：4 倍放大渲染 -> 按墨迹 bbox 裁剪 -> 缩放到 8x8 -> 二值化。
    直接在小画布上渲染会因 hinting 丢笔画，所以先放大再降采样。
    """
    SS = 4
    big = SIZE * SS * 2
    img = Image.new("L", (big, big), 0)
    draw = ImageDraw.Draw(img)
    font = ImageFont.truetype(str(font_path), SIZE * SS)
    draw.text((big // 4, big // 4), ch, fill=255, font=font)

    # 裁到墨迹 bbox
    bbox = img.getbbox()
    if bbox is None:
        return [0] * SIZE, 0, 0
    ink = img.crop(bbox)
    tw, th = ink.size

    # 裁好的墨迹直接缩放到 8x8（保持长宽比，居中）
    scale = min(SIZE / tw, SIZE / th)
    nw = max(1, min(SIZE, int(round(tw * scale))))
    nh = max(1, min(SIZE, int(round(th * scale))))
    rs = ink.resize((nw, nh), Image.LANCZOS)

    small = Image.new("L", (SIZE, SIZE), 0)
    small.paste(rs, ((SIZE - nw) // 2, (SIZE - nh) // 2))
    return small, tw, th


def to_bitmap(small: Image.Image, thresh: int = 64) -> list[int]:
    """灰度图 -> 每行一个 8bit 值（bit7 = 最左像素）。"""
    rows: list[int] = []
    px = small.load()
    for y in range(SIZE):
        v = 0
        for x in range(SIZE):
            if px[x, y] >= thresh:
                v |= 1 << (7 - x)
        rows.append(v)
    return rows


def write_bdf(chars: list[str], font_path: Path, out: Path, thresh: int) -> None:
    lines: list[str] = [
        "STARTFONT 2.1",
        f"FONT -Meowth-Small8-Medium-R-Normal--{SIZE}-{SIZE*10}-75-75-C-80-ISO10646-1",
        f"SIZE {SIZE} 75 75",
        f"FONTBOUNDINGBOX {SIZE} {SIZE} 0 0",
        "STARTPROPERTIES 4",
        f"FONT_ASCENT {SIZE}",
        "FONT_DESCENT 0",
        f"PIXEL_SIZE {SIZE}",
        'COMMENT "Generated by scripts/gen_small8_bdf.py: native 8x8 dot matrix '
        'rasterized from system TTF at 8px, NOT downscaled from 9x9"',
        "ENDPROPERTIES",
        f"CHARS {len(chars)}",
        "",
    ]
    for ch in chars:
        enc = ord(ch)
        small, _tw, _th = render_glyph(ch, font_path)
        rows = to_bitmap(small, thresh)
        lines.append(f"STARTCHAR U+{enc:04X}")
        lines.append(f"ENCODING {enc}")
        lines.append("SWIDTH 500 0")
        lines.append(f"DWIDTH {SIZE} 0")
        lines.append(f"BBX {SIZE} {SIZE} 0 0")
        lines.append("BITMAP")
        for v in rows:
            lines.append(f"{v:02X}")
        lines.append("ENDCHAR")
        lines.append("")
    lines.append("ENDFONT")
    lines.append("")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--charmap", required=True, type=Path)
    ap.add_argument("--font", default=r"C:\Windows\Fonts\simsun.ttc", type=Path)
    ap.add_argument("--thresh", type=int, default=64,
                    help="二值化阈值 0..255，越小笔画越多")
    a = ap.parse_args()

    if not a.font.is_file():
        raise SystemExit(f"字体不存在: {a.font}")
    chars = load_charset(a.charmap)
    print(f"字符集 {len(chars)} 个（来自 {a.charmap.name}）")
    print(f"源字体 {a.font.name}，目标 {SIZE}x{SIZE}，阈值 {a.thresh}")
    write_bdf(chars, a.font, a.out, a.thresh)
    print(f"已写出 {a.out}  ({a.out.stat().st_size} 字节)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
